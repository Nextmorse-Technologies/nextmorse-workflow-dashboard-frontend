export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState(() => {
    try {
      const saved = localStorage.getItem('nextmorse_dash_locale');
      return saved === 'ne' || saved === 'en' ? saved : 'en';
    } catch {
      return 'en';
    }
  });
  const setLocale = (next) => {
    const value = next === 'ne' ? 'ne' : 'en';
    setLocaleState(value);
    try {
      localStorage.setItem('nextmorse_dash_locale', value);
    } catch {
      /* Private browsing or blocked storage — the toggle still
         works for this session. */
    }
  };
  const value = {
    locale,
    setLocale,
    t: (key, vars) => translate(key, locale, vars),
    money: (n) => formatMoney(n, locale),
    digits: (v) => (locale === 'ne' ? toNepaliDigits(v) : String(v)),
  };
  /* createElement, not JSX: this file is .js, and Vite does not
     parse JSX in .js files — the build failed on this line. */
  return createElement(LocaleContext.Provider, { value }, children);
}

export function useLocale() {
  return useContext(LocaleContext);
}
