/* Locale for the React dashboard — English or Nepali, Devanagari
 * wherever possible (Bijaya, 24 Nov 2026: "follow locale in every
 * component please, there should be either english or nepali, if
 * possible use all devnagiri").
 *
 * The dictionary is keyed by the English string itself, so a
 * missing translation falls back to English instead of a blank
 * or a broken key. Translations are harvested from the Laravel
 * lang files (lang/en|ne/dashboard.php) where the same words
 * already exist, so both dashboards say the same thing; the
 * rest are written here. Amounts render as NPR in English and
 * नेरू with Devanagari digits in Nepali; counts and years go
 * through digits() the same way. Dates stay as the API sends
 * them (BS-first already); client names, services and other
 * recorded data are never translated — they are the record.
 *
 * The choice persists in localStorage across sessions. */

const DEVANAGARI = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

export function toNepaliDigits(value) {
  return String(value).replace(/[0-9]/g, (d) => DEVANAGARI[Number(d)]);
}

export function formatMoney(n, locale) {
  if (n === null || n === undefined || n === '') return '—';
  const num = Number(n);
  if (Number.isNaN(num)) return '—';
  const grouped = num.toLocaleString('en-US', {
    minimumFractionDigits: 2, maximumFractionDigits: 2,
  });
  return locale === 'ne' ? 'नेरू ' + toNepaliDigits(grouped) : 'NPR ' + grouped;
}

