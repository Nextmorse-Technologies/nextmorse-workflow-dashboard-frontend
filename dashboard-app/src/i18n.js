export function translate(key, locale, vars) {
  let s = locale === 'ne' ? (STRINGS[key] ?? key) : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

